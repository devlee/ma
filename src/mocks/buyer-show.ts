interface SeedSub {
  id: string;
  mainTaskId: string;
  color: string;
  angle: Subtask['angle'];
  crowdTag: CrowdTag;
  sceneTag: string;
  img1Source: Image1Source;
  img2: string;
  img3?: string;
  prompt: string;
  templateVersion: string;
  status: SubtaskStatus;
  reviewRound: number;
  generateCount: number;
  assignee: string;
  createdAt: string;
  remark?: string;
  versions?: Subtask['versions'];
  reviewRecords?: Subtask['reviewRecords'];
  operationLogs?: Subtask['operationLogs'];
}

function toSub(seed: SeedSub, mains: MainTask[]): Subtask {
  const main = mains.find((m) => m.id === seed.mainTaskId);
  return {
    id: seed.id,
    mainTaskId: seed.mainTaskId,
    spu: main?.spu ?? '',
    color: seed.color,
    angle: seed.angle,
    category: main?.category ?? '',
    crowdTag: seed.crowdTag,
    sceneTag: seed.sceneTag,
    produceMode: main?.produceMode ?? '批量制作',
    status: seed.status,
    reviewRound: seed.reviewRound,
    generateCount: seed.generateCount,
    assignee: seed.assignee,
    createdAt: seed.createdAt,
    image1: { url: `img1-${seed.id}`, source: seed.img1Source },
    image2: {
      url: `img2-${seed.img2}`,
      materialId: seed.img2,
      tags: `${main?.category ?? ''} / ${seed.angle} / ${seed.sceneTag}`,
    },
    image3: seed.img3
      ? {
          url: `img3-${seed.img3}`,
          materialId: seed.img3,
          tags: `${main?.category ?? ''} / ${seed.angle} / ${seed.sceneTag}`,
        }
      : undefined,
    prompt: seed.prompt,
    templateVersion: seed.templateVersion,
    colorMatchStatus: deriveColorMatchStatus(seed.color, mockColorDictionaries),
    currentResultUrl: seed.status === '生图中' || seed.status === '生图失败' ? undefined : `result-${seed.id}`,
    versions: seed.versions,
    remark: seed.remark,
    reviewRecords: seed.reviewRecords,
    operationLogs: seed.operationLogs,
  };
}

